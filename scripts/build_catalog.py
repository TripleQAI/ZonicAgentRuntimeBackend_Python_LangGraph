"""Build ``tests/catalog.yaml`` from the design's sanity catalog and the plan's task rows.

Case IDs come from the design (Section 19.2), the plan's review additions
(Section 2) and the plan's fixture cases (Section 20.3). The tasks that prove
each case come from the "Proves" column of the plan's task tables. Cases no task
proves are reported, so a gap in the plan is visible instead of silent.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / "docs" / "zonic-agent-runtime-langgraph-architecture-design.md"
PLAN = ROOT / "docs" / "zonic-agent-runtime-langgraph-implementation-plan.md"
CATALOG = ROOT / "tests" / "catalog.yaml"

CASE = r"[A-Z]-\d\d"
ROW_ID = re.compile(rf"^\| ({CASE})(?: to ({CASE}))? \| (.+?) \|")
TASK_ROW = re.compile(r"^\| (P\d-\d\d) \| ([^|]+) \|")


def expand(first: str, last: str | None) -> list[str]:
    if last is None:
        return [first]
    group, a, b = first[0], int(first[2:]), int(last[2:])
    if last[0] != group or b < a:
        raise ValueError(f"bad range {first} to {last}")
    return [f"{group}-{n:02d}" for n in range(a, b + 1)]


def ids_in(text: str) -> list[str]:
    """Every case ID in a cell, expanding 'X-01 to X-05' ranges."""
    found: list[str] = []
    for m in re.finditer(rf"({CASE})(?: to ({CASE}))?", text):
        found.extend(expand(m.group(1), m.group(2)))
    return found


def design_cases() -> dict[str, str]:
    lines = DESIGN.read_text(encoding="utf-8").splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith("### 19.2"))
    end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith("## "))
    cases: dict[str, str] = {}
    for line in lines[start:end]:
        m = ROW_ID.match(line)
        if m:
            for case in expand(m.group(1), m.group(2)):
                cases[case] = m.group(3).strip()
    return cases


def plan_additions() -> dict[str, str]:
    lines = PLAN.read_text(encoding="utf-8").splitlines()
    cases: dict[str, str] = {}
    in_findings = False
    for line in lines:
        if line.startswith("### 2.2"):
            in_findings = True
        elif line.startswith("## 3."):
            in_findings = False
        if in_findings and line.startswith("| DR-"):
            last_cell = line.strip().strip("|").split("|")[-1]
            for case in ids_in(last_cell):
                cases.setdefault(case, f"Plan finding {line.split('|')[1].strip()}")
    start = next(i for i, line in enumerate(lines) if line.startswith("### 20.3"))
    for line in lines[start:]:
        if line.startswith("### 20.4"):
            break
        m = ROW_ID.match(line)
        if m:
            cases[m.group(1)] = m.group(3).strip()
    return cases


def task_proofs() -> dict[str, list[str]]:
    proofs: dict[str, list[str]] = {}
    for line in PLAN.read_text(encoding="utf-8").splitlines():
        m = TASK_ROW.match(line)
        if not m:
            continue
        cells = line.strip().strip("|").split("|")
        proves = cells[-1]
        for case in ids_in(proves):
            proofs.setdefault(case, [])
            if m.group(1) not in proofs[case]:
                proofs[case].append(m.group(1))
    return proofs


def build() -> tuple[dict[str, object], list[str], list[str]]:
    cases = {**design_cases(), **plan_additions()}
    proofs = task_proofs()
    unproved = sorted(c for c in cases if c not in proofs)
    unknown = sorted(c for c in proofs if c not in cases)
    catalog = {
        "comment": "Generated by scripts/build_catalog.py from the design and plan. Do not edit by hand.",
        "cases": {c: {"title": cases[c], "tasks": proofs.get(c, [])} for c in sorted(cases)},
    }
    return catalog, unproved, unknown


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    catalog, unproved, unknown = build()
    text = yaml.safe_dump(catalog, sort_keys=False, allow_unicode=True, width=200)
    for case in unproved:
        print(f"no task proves {case}")
    for case in unknown:
        print(f"task proves an ID the catalog does not define: {case}")
    if args.check:
        current = CATALOG.read_text(encoding="utf-8") if CATALOG.exists() else ""
        if current != text:
            print("tests/catalog.yaml is out of date: run uv run python -m scripts.build_catalog")
            return 1
        return 1 if unknown else 0
    CATALOG.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(catalog['cases'])} cases")  # type: ignore[arg-type]
    return 1 if unknown else 0


if __name__ == "__main__":
    sys.exit(main())
